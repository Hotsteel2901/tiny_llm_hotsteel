QUESTION_PREFIXES = ["请问", "我想知道", "能不能告诉我", "想问一下", ""]
QUESTION_SUFFIXES = ["？", "呢？", "，可以吗？", ""]


def _fill_facts(rng: random.Random, extra: int) -> List[Dict[str, str]]:
    out: List[Dict[str, str]] = []
    for topic, tmpl_q, tmpl_a in FACT_TEMPLATES:
        for x, desc, desc_short in FACTS:
            # 剥离 desc 开头的实体名，避免「太阳是太阳是……」的重复
            desc_clean = desc
            for prefix in (f"{x}是", f"{x}指", x):
                if desc_clean.startswith(prefix):
                    desc_clean = desc_clean[len(prefix):]
                    break
            ctx = _default_ctx()
            ctx.update(x=x, desc=desc_clean, desc_short=desc_short)
            q = tmpl_q.format(**ctx)
            a = tmpl_a.format(**ctx)
            if not a.strip() or "{" in a or "}" in a:
                continue
            out.append({"instruction": q, "response": a, "category": topic})
    return out


def _default_ctx() -> Dict[str, str]:
    """为各类模板提供默认占位符，缺省即空串。"""
    return {
        "x": "", "desc": "", "desc_short": "",
        "y": "", "y_reason": "",
        "z": "", "z_how": "",
    }


def _fill_reasons(rng: random.Random) -> List[Dict[str, str]]:
    out = []
    for y, reason in REASONS:
        for tmpl in ("为什么{y}？", "{y}是怎么回事？", "请解释{y}的原因。"):
            out.append({
                "instruction": tmpl.format(y=y),
                "response": reason,
                "category": "科学",
            })
    return out


def _fill_hows(rng: random.Random) -> List[Dict[str, str]]:
    out = []
    for z, how in HOWS:
        for tmpl in ("{z}应该怎么做？", "怎样{z}？", "{z}有什么建议？"):
            out.append({
                "instruction": tmpl.format(z=z),
                "response": how,
                "category": "生活",
            })
    return out


def _expand_multi_ask(rng: random.Random, base: List[Dict[str, str]],
                      extra_per: int) -> List[Dict[str, str]]:
    """对既有问答做多问法改写，增加问法多样性。"""
    out = list(base)
    for it in base:
        core = it["instruction"].rstrip("？?。.，,！!")
        for _ in range(extra_per):
            pre = rng.choice(QUESTION_PREFIXES)
            suf = rng.choice(QUESTION_SUFFIXES)
            nq = f"{pre}{core}{suf}".strip()
            if nq and nq != it["instruction"]:
                out.append({
                    "instruction": nq,
                    "response": it["response"],
                    "category": it["category"],
                })
    return out


def _fill_compares(rng: random.Random) -> List[Dict[str, str]]:
    out: List[Dict[str, str]] = []
    for a, b, fa, fb, diff in COMPARES:
        q1 = f"{a}和{b}有什么区别？"
        q2 = f"{a}与{b}有什么不同？"
        ans = f"{a}和{b}的主要区别是：{fa}；而{fb}。{diff}。"
        out.append({"instruction": q1, "response": ans, "category": "常识"})
        out.append({"instruction": q2, "response": ans, "category": "常识"})
    return out


def _fill_self(rng: random.Random) -> List[Dict[str, str]]:
    return [
        {"instruction": q, "response": a, "category": "语言"}
        for q, a in SELF_QA
    ]


def _fill_chitchat(rng: random.Random) -> List[Dict[str, str]]:
    """日常短句：正向加入，且**不做多问法改写**以保持简短精确。"""
    return [
        {"instruction": q, "response": a, "category": "语言"}
        for q, a in CHITCHAT_QA
    ]


def render_corpus(rng: random.Random,
                  teacher: Callable[[str], str] | None = None,
                  extra_per: int = 3) -> List[Dict[str, str]]:
    """生成教师语料。

    ``teacher`` 若提供，则用它重写所有回答（真实蒸馏）；否则使用内置知识库。
    """
    records: List[Dict[str, str]] = []
    # 1) 种子问答
    for cat, q, r in SEED_QA:
        records.append({"instruction": q, "response": r, "category": cat})
    # 2) 事实 / 原因 / 做法 / 对比 / 自我认知
    records.extend(_fill_facts(rng, extra_per))
    records.extend(_fill_reasons(rng))
    records.extend(_fill_hows(rng))
    records.extend(_fill_compares(rng))
    records.extend(_fill_self(rng))
    # 3) 多问法扩增（不含日常短句，它们保持原样）
    records = _expand_multi_ask(rng, records, extra_per)
    # 4) 日常礼貌短句：多次加权加入，避免被长句语料稀释
    chit = _fill_chitchat(rng)
    for _ in range(4):
        records.extend(chit)

    # 4) 教师重写（可选）
    if teacher is not None:
        for it in records:
            try:
                it["response"] = str(teacher(it["instruction"])).strip() or it["response"]
            except Exception as exc:  # noqa: BLE001
                print(f"  [教师调用失败] {it['instruction']}: {exc}")

    # 去重
    seen = set()
    uniq = []
    for it in records:
        key = (it["instruction"], it["response"])
        if key in seen:
            continue
        seen.add(key)
        uniq.append(it)
    rng.shuffle(uniq)
    return uniq


def main() -> None:
    ap = argparse.ArgumentParser(description="生成教师问答语料")
    ap.add_argument("--out", default="data/teacher_qa.jsonl")
    ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--extra_per", type=int, default=3)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    records = render_corpus(rng, teacher=None, extra_per=args.extra_per)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")

    cats: Dict[str, int] = {}
    for it in records:
        cats[it["category"]] = cats.get(it["category"], 0) + 1
    print(f"已生成 {len(records)} 条教师语料 -> {args.out}")
    for c, n in sorted(cats.items(), key=lambda x: -x[1]):
        print(f"  {c}: {n}")


if __name__ == "__main__":
    main()
