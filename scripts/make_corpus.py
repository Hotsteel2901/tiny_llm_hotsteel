# ---------------------------------------------------------------------------
# 2) 多问法模板扩增
# ---------------------------------------------------------------------------
QUESTION_PREFIXES = ["请问", "我想知道", "能不能告诉我", "想问一下", ""]
QUESTION_SUFFIXES = ["？", "呢？", "，可以吗？", ""]


def expand_politeness(q: str, r: str, rng: random.Random,
                      n_extra: int) -> List[Tuple[str, str]]:
    """礼貌化扩增：改变问法保持答案。"""
    outs = [(q, r)]
    for _ in range(n_extra):
        pre = rng.choice(QUESTION_PREFIXES)
        suf = rng.choice(QUESTION_SUFFIXES)
        nq = f"{pre}{q.rstrip('？?')}{suf}".strip()
        if nq and nq not in (o[0] for o in outs):
            outs.append((nq, r))
    return outs


# 数值型模板：可控数量，避免压过其他类别
def gen_arithmetic(rng: random.Random, n: int) -> List[Tuple[str, str]]:
    outs = []
    for _ in range(n):
        a = rng.randint(1, 20)
        b = rng.randint(1, 20)
        r = rng.random()
        if r < 0.4:
            q = f"{a}加{b}等于多少？"
            ans = f"{a}加{b}等于{a + b}。"
        elif r < 0.8:
            hi, lo = max(a, b), min(a, b)
            q = f"{hi}减{lo}等于多少？"
            ans = f"{hi}减{lo}等于{hi - lo}。"
        else:
            q = f"{a}乘以{b}等于多少？"
            ans = f"{a}乘以{b}等于{a * b}。"
        outs.append(("算术", q, ans))
    return outs


def build_corpus(rng: random.Random,
                 n_arith: int = 150,
                 extra_per_seed: int = 4) -> List[Dict[str, str]]:
    """合并种子问答 + 扩增 + 少量算术数据，去重后返回。"""
    pairs: List[Tuple[str, str, str]] = []
    for cat, q, r in SEED_QA:
        for nq, nr in expand_politeness(q, r, rng, extra_per_seed):
            pairs.append((cat, nq, nr))
    pairs.extend(gen_arithmetic(rng, n_arith))

    seen = set()
    records: List[Dict[str, str]] = []
    for cat, q, r in pairs:
        key = (q.strip(), r.strip())
        if key in seen:
            continue
        seen.add(key)
        records.append({
            "instruction": q.strip(),
            "response": r.strip(),
            "category": cat,
        })
    rng.shuffle(records)
    return records


def main() -> None:
    ap = argparse.ArgumentParser(description="生成 hotsteel0.1 中文问答语料")
    ap.add_argument("--out", default="data/corpus_zh.jsonl")
    ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--n_arith", type=int, default=150, help="算术模板生成条数")
    ap.add_argument("--extra_per_seed", type=int, default=4, help="每个种子问题的多问法扩增数")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    records = build_corpus(rng, n_arith=args.n_arith, extra_per_seed=args.extra_per_seed)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")

    cats: Dict[str, int] = {}
    for rec in records:
        cats[rec["category"]] = cats.get(rec["category"], 0) + 1
    total = len(records)
    print(f"已生成 {total} 条语料 -> {args.out}")
    for c, n in sorted(cats.items(), key=lambda x: -x[1]):
        print(f"  {c}: {n}  ({n / total * 100:.1f}%)")


if __name__ == "__main__":
    main()
